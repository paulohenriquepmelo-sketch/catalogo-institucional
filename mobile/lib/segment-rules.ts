/**
 * Segmentos de clientes do app. ARQUIVO GERADO: edite
 * `scripts/segmentos/segrules.py` e rode `gen.py` (veja o LEIA-ME.md de lá),
 * que também confere as regras contra o catálogo publicado.
 *
 * Diferente do site, um produto pode estar em VÁRIOS segmentos: a sacola
 * serve para a padaria, o restaurante e o delivery. Cada segmento é dividido
 * em grupos (insumos, embalagens, revenda...).
 *
 * Um grupo inclui o produto quando a CATEGORIA dele está em `categories` OU o
 * NOME tem alguma palavra de `keywords`, e o nome não tem nenhuma de
 * `exclude`. As palavras casam pelo início ("sacola" pega "sacolas"); um
 * espaço no fim exige a palavra inteira ("copo " não pega "Copobras").
 * Acentos e maiúsculas são ignorados.
 *
 * `minSize` (gramas ou ml, 0 = sem limite) exige embalagem grande, lida do
 * nome ("3,4KG", "900ML", "5,01 LTS"): é o que separa o insumo food service
 * (balde, galão, saco de 25 kg) do item de prateleira. Sem tamanho no nome, o
 * produto só entra se tiver "bag", "galão", "balde" ou "(GR)".
 *
 * `within` (vazio = sem limite) restringe o grupo às categorias listadas:
 * "mac " só vale para macarrão, não para "ESCOLVA ... MAC." (escova macia).
 */

